-- Схема для чистой установки (выполняется один раз при первом старте контейнера).
-- Для уже существующей БД используйте docker/postgres/migrations/.

-- ===================== География мира =====================
-- Город — основная географическая сущность. Регионов в архитектуре нет: ни таблицы, ни region_id,
-- ни наследования риска. Локация принадлежит ровно одному городу (locations.city_id).
-- Названия, уровни открытия, коэффициенты риска и параметры календаря — это данные (UPDATE),
-- игровая логика читает их из БД и не содержит захардкоженных городов.
-- Города, локации и события хранятся постоянно: каскадных удалений нет, закрытие события
-- только меняет доступность (см. world_city_access).

-- События мира (календарь праздничных городов). Окно события хранится вместе с часовым поясом (IANA);
-- история запусков — в world_event_runs. min_level — минимальный уровень персонажа для входа.
CREATE TABLE IF NOT EXISTS world_events (
    id          SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(40)  NOT NULL,
    name        VARCHAR(80)  NOT NULL,
    min_level   SMALLINT     NOT NULL DEFAULT 1 CHECK (min_level BETWEEN 1 AND 50),
    timezone    VARCHAR(64)  NOT NULL DEFAULT 'UTC',
    starts_at   TIMESTAMPTZ,
    ends_at     TIMESTAMPTZ,
    -- unscheduled: даты не заданы; scheduled: окно задано, ждёт начала; active: идёт;
    -- finished: завершено; cancelled: отменено (город остаётся закрытым).
    status      VARCHAR(12)  NOT NULL DEFAULT 'unscheduled'
                CHECK (status IN ('unscheduled', 'scheduled', 'active', 'finished', 'cancelled')),
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT world_events_code_key UNIQUE (code),
    CONSTRAINT world_events_code_format CHECK (code ~ '^[a-z][a-z0-9_]{1,39}$'),
    CONSTRAINT world_events_window CHECK (starts_at IS NULL OR ends_at IS NULL OR ends_at > starts_at),
    CONSTRAINT world_events_window_required CHECK (
        status NOT IN ('scheduled', 'active') OR (starts_at IS NOT NULL AND ends_at IS NOT NULL)
    )
);

-- Города: 20 постоянных (kind = 'permanent') и 3 города событий (kind = 'event').
-- unlock_level — минимальный уровень персонажа для доступа в город.
CREATE TABLE IF NOT EXISTS cities (
    id              SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR(40)  NOT NULL,
    name            VARCHAR(80)  NOT NULL,
    kind            VARCHAR(9)   NOT NULL DEFAULT 'permanent' CHECK (kind IN ('permanent', 'event')),
    unlock_level    SMALLINT     NOT NULL CHECK (unlock_level BETWEEN 1 AND 50),
    is_start        BOOLEAN      NOT NULL DEFAULT FALSE,
    world_event_id  SMALLINT     REFERENCES world_events(id) ON DELETE RESTRICT,
    sort_order      SMALLINT     NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT cities_code_key UNIQUE (code),
    CONSTRAINT cities_code_format CHECK (code ~ '^[a-z][a-z0-9_]{1,39}$'),
    CONSTRAINT cities_event_link CHECK ((kind = 'event') = (world_event_id IS NOT NULL)),
    CONSTRAINT cities_start_rules CHECK (NOT is_start OR (kind = 'permanent' AND unlock_level = 1))
);

-- Ровно один стартовый город; у каждого события — не более одного города.
CREATE UNIQUE INDEX IF NOT EXISTS cities_one_start ON cities (is_start) WHERE is_start;
CREATE UNIQUE INDEX IF NOT EXISTS cities_one_per_event ON cities (world_event_id) WHERE world_event_id IS NOT NULL;

-- Локации: принадлежат городу напрямую (city_id). Уровень доступа локации хранится отдельно от города;
-- required_quest_code — необязательное требование квеста для опасных локаций (таблицы квестов пока нет).
-- risk_coefficient — собственный коэффициент локации 0.00–1.00, от города не наследуется:
--   0.00 нет риска · 0.05 низкий · 0.10 умеренный · 0.15–0.20 высокий · 0.25–0.30 очень высокий · 0.35–0.40 критический.
-- Задел под баланс: P_effective = P_base · (1 + risk_coefficient) (индекс, не формула здоровья или урона).
CREATE TABLE IF NOT EXISTS locations (
    id                  SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_id             SMALLINT     NOT NULL REFERENCES cities(id) ON DELETE RESTRICT,
    code                VARCHAR(48)  NOT NULL,
    name                VARCHAR(80)  NOT NULL,
    sort_order          SMALLINT     NOT NULL CHECK (sort_order >= 1),
    unlock_level        SMALLINT     NOT NULL CHECK (unlock_level BETWEEN 1 AND 50),
    required_quest_code VARCHAR(48),
    risk_coefficient    NUMERIC(3,2) NOT NULL DEFAULT 0 CHECK (risk_coefficient BETWEEN 0 AND 1),
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    CONSTRAINT locations_code_key UNIQUE (code),
    CONSTRAINT locations_code_format CHECK (code ~ '^[a-z][a-z0-9_]{1,47}$'),
    CONSTRAINT locations_city_order_key UNIQUE (city_id, sort_order)
);

-- История запусков событий. Строка создаётся при открытии события и закрывается при его окончании;
-- окно, часовой пояс и min_level фиксируются на момент запуска.
CREATE TABLE IF NOT EXISTS world_event_runs (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    world_event_id  SMALLINT     NOT NULL REFERENCES world_events(id) ON DELETE RESTRICT,
    starts_at       TIMESTAMPTZ  NOT NULL,
    ends_at         TIMESTAMPTZ  NOT NULL,
    timezone        VARCHAR(64)  NOT NULL,
    min_level       SMALLINT     NOT NULL CHECK (min_level BETWEEN 1 AND 50),
    status          VARCHAR(10)  NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'finished', 'cancelled')),
    opened_at       TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    closed_at       TIMESTAMPTZ,
    CONSTRAINT world_event_runs_window CHECK (ends_at > starts_at),
    CONSTRAINT world_event_runs_closed CHECK ((status = 'active') = (closed_at IS NULL))
);

CREATE UNIQUE INDEX IF NOT EXISTS world_event_runs_one_active ON world_event_runs (world_event_id) WHERE status = 'active';
CREATE INDEX IF NOT EXISTS world_event_runs_event_recent ON world_event_runs (world_event_id, id DESC);

-- updated_at обновляется автоматически.
CREATE OR REPLACE FUNCTION world_touch_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at := NOW();
    RETURN NEW;
END
$$;

DROP TRIGGER IF EXISTS world_events_touch ON world_events;
CREATE TRIGGER world_events_touch BEFORE UPDATE ON world_events FOR EACH ROW EXECUTE FUNCTION world_touch_updated_at();
DROP TRIGGER IF EXISTS cities_touch ON cities;
CREATE TRIGGER cities_touch BEFORE UPDATE ON cities FOR EACH ROW EXECUTE FUNCTION world_touch_updated_at();
DROP TRIGGER IF EXISTS locations_touch ON locations;
CREATE TRIGGER locations_touch BEFORE UPDATE ON locations FOR EACH ROW EXECUTE FUNCTION world_touch_updated_at();

-- Часовой пояс события — существующее имя IANA (CHECK не умеет подзапросов, поэтому триггер).
CREATE OR REPLACE FUNCTION world_events_check_timezone() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_timezone_names WHERE name = NEW.timezone) THEN
        RAISE EXCEPTION 'Unknown time zone: %', NEW.timezone USING ERRCODE = '22023';
    END IF;
    RETURN NEW;
END
$$;

DROP TRIGGER IF EXISTS world_events_timezone ON world_events;
CREATE TRIGGER world_events_timezone BEFORE INSERT OR UPDATE OF timezone ON world_events
    FOR EACH ROW EXECUTE FUNCTION world_events_check_timezone();

-- Города и локации событий, сами события и история запусков постоянны: удалять их нельзя.
-- Завершение события только закрывает доступ (world_city_access), строки остаются.
CREATE OR REPLACE FUNCTION world_protect_event_content() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_TABLE_NAME = 'world_events' OR TG_TABLE_NAME = 'world_event_runs' THEN
        RAISE EXCEPTION '% rows are permanent and cannot be deleted', TG_TABLE_NAME USING ERRCODE = '23001';
    ELSIF TG_TABLE_NAME = 'cities' AND OLD.kind = 'event' THEN
        RAISE EXCEPTION 'Event city % is permanent and cannot be deleted', OLD.code USING ERRCODE = '23001';
    ELSIF TG_TABLE_NAME = 'locations' AND EXISTS (SELECT 1 FROM cities c WHERE c.id = OLD.city_id AND c.kind = 'event') THEN
        RAISE EXCEPTION 'Event location % is permanent and cannot be deleted', OLD.code USING ERRCODE = '23001';
    END IF;
    RETURN OLD;
END
$$;

DROP TRIGGER IF EXISTS world_events_protect ON world_events;
CREATE TRIGGER world_events_protect BEFORE DELETE ON world_events FOR EACH ROW EXECUTE FUNCTION world_protect_event_content();
DROP TRIGGER IF EXISTS world_event_runs_protect ON world_event_runs;
CREATE TRIGGER world_event_runs_protect BEFORE DELETE ON world_event_runs FOR EACH ROW EXECUTE FUNCTION world_protect_event_content();
DROP TRIGGER IF EXISTS cities_protect ON cities;
CREATE TRIGGER cities_protect BEFORE DELETE ON cities FOR EACH ROW EXECUTE FUNCTION world_protect_event_content();
DROP TRIGGER IF EXISTS locations_protect ON locations;
CREATE TRIGGER locations_protect BEFORE DELETE ON locations FOR EACH ROW EXECUTE FUNCTION world_protect_event_content();

-- Событие открыто: не отменено, окно задано и p_at внутри [starts_at, ends_at).
-- Статус 'finished' закрывает событие досрочно; задержка фоновой синхронизации на доступ не влияет.
CREATE OR REPLACE FUNCTION world_event_is_open(p_event_id SMALLINT, p_at TIMESTAMPTZ DEFAULT NOW())
RETURNS BOOLEAN LANGUAGE sql STABLE AS $$
    SELECT EXISTS (
        SELECT 1 FROM world_events e
        WHERE e.id = p_event_id
          AND e.status IN ('scheduled', 'active')
          AND e.starts_at <= p_at AND p_at < e.ends_at
    )
$$;

-- Доступ персонажа уровня p_level в город: уровень не ниже unlock_level города (для города события —
-- и не ниже min_level события) и, для города события, событие открыто.
CREATE OR REPLACE FUNCTION world_city_access(p_city_id SMALLINT, p_level INTEGER, p_at TIMESTAMPTZ DEFAULT NOW())
RETURNS BOOLEAN LANGUAGE sql STABLE AS $$
    SELECT COALESCE((
        SELECT p_level >= GREATEST(c.unlock_level, COALESCE(e.min_level, 1))
               AND (c.world_event_id IS NULL OR world_event_is_open(c.world_event_id, p_at))
        FROM cities c
        LEFT JOIN world_events e ON e.id = c.world_event_id
        WHERE c.id = p_city_id
    ), FALSE)
$$;

-- Доступ в локацию: доступ в её город + собственный уровень локации + (если задан) выполненный квест.
CREATE OR REPLACE FUNCTION world_location_access(
    p_location_id SMALLINT, p_level INTEGER, p_at TIMESTAMPTZ DEFAULT NOW(), p_completed_quests TEXT[] DEFAULT '{}'
) RETURNS BOOLEAN LANGUAGE sql STABLE AS $$
    SELECT COALESCE((
        SELECT world_city_access(l.city_id, p_level, p_at)
               AND p_level >= l.unlock_level
               AND (l.required_quest_code IS NULL OR l.required_quest_code = ANY (p_completed_quests))
        FROM locations l
        WHERE l.id = p_location_id
    ), FALSE)
$$;

-- Назначить окно события (новый запуск). Активное событие менять нельзя — сначала завершить.
CREATE OR REPLACE FUNCTION world_event_schedule(
    p_event_id SMALLINT, p_starts_at TIMESTAMPTZ, p_ends_at TIMESTAMPTZ, p_timezone VARCHAR DEFAULT NULL
) RETURNS VOID LANGUAGE plpgsql AS $$
DECLARE
    v_status VARCHAR;
BEGIN
    SELECT status INTO v_status FROM world_events WHERE id = p_event_id FOR UPDATE;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'World event % not found', p_event_id USING ERRCODE = 'P0002';
    END IF;
    IF v_status = 'active' THEN
        RAISE EXCEPTION 'World event % is active; finish it before rescheduling', p_event_id USING ERRCODE = '55000';
    END IF;
    UPDATE world_events
       SET starts_at = p_starts_at,
           ends_at   = p_ends_at,
           timezone  = COALESCE(p_timezone, timezone),
           status    = 'scheduled'
     WHERE id = p_event_id;
END
$$;

-- Синхронизация статусов и истории запусков с календарём. Идемпотентна; вызывается backend'ом по таймеру.
-- 1) scheduled с началом ≤ now → active + строка истории; 2) active с концом ≤ now → finished + закрытие строки.
-- Города и локации при этом не изменяются и не удаляются.
CREATE OR REPLACE FUNCTION world_events_sync(p_now TIMESTAMPTZ DEFAULT NOW(), OUT opened INTEGER, OUT closed INTEGER)
LANGUAGE plpgsql AS $$
BEGIN
    WITH due AS (
        UPDATE world_events
           SET status = 'active'
         WHERE status = 'scheduled' AND starts_at <= p_now
        RETURNING id, starts_at, ends_at, timezone, min_level
    ), ins AS (
        INSERT INTO world_event_runs (world_event_id, starts_at, ends_at, timezone, min_level, opened_at)
        SELECT id, starts_at, ends_at, timezone, min_level, p_now FROM due
        RETURNING 1
    )
    SELECT COUNT(*) INTO opened FROM ins;

    WITH done AS (
        UPDATE world_events
           SET status = 'finished'
         WHERE status = 'active' AND ends_at <= p_now
        RETURNING id
    ), runs AS (
        UPDATE world_event_runs r
           SET status = 'finished', closed_at = p_now
          FROM done
         WHERE r.world_event_id = done.id AND r.status = 'active'
        RETURNING 1
    )
    SELECT COUNT(*) INTO closed FROM done;
END
$$;

-- Стартовый город нового персонажа (cities.is_start) — значение по умолчанию users.current_city_id.
CREATE OR REPLACE FUNCTION world_start_city_id() RETURNS SMALLINT LANGUAGE sql STABLE AS $$
    SELECT id FROM cities WHERE is_start
$$;

