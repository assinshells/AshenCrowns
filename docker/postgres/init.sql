-- Проверки целостности мира: SELECT * FROM world_integrity_report(); — все строки должны иметь ok = TRUE.
-- Те же проверки выполняет backend/test/world.test.js.
CREATE OR REPLACE FUNCTION world_integrity_report()
RETURNS TABLE (check_code TEXT, ok BOOLEAN, details TEXT) LANGUAGE plpgsql STABLE AS $$
DECLARE
    v_n INTEGER;
    v_min SMALLINT;
    v_max SMALLINT;
    v_list TEXT;
BEGIN
    -- 1. Ровно 20 основных городов и 3 города событий.
    SELECT COUNT(*) INTO v_n FROM cities WHERE kind = 'permanent';
    check_code := 'permanent_cities_count'; ok := v_n = 20; details := 'found ' || v_n; RETURN NEXT;
    SELECT COUNT(*) INTO v_n FROM cities WHERE kind = 'event';
    check_code := 'event_cities_count'; ok := v_n = 3; details := 'found ' || v_n; RETURN NEXT;

    -- 2. У каждого события ровно один город, у каждого города события — событие.
    SELECT COUNT(*) INTO v_n FROM world_events e WHERE (SELECT COUNT(*) FROM cities c WHERE c.world_event_id = e.id) <> 1;
    check_code := 'each_event_has_one_city'; ok := v_n = 0; details := v_n || ' events violate'; RETURN NEXT;

    -- 3. По четыре локации у каждого города (начальный этап).
    SELECT COUNT(*), string_agg(code, ', ') INTO v_n, v_list
      FROM cities c WHERE (SELECT COUNT(*) FROM locations l WHERE l.city_id = c.id) <> 4;
    check_code := 'four_locations_per_city'; ok := v_n = 0; details := COALESCE(v_list, 'all cities have 4'); RETURN NEXT;

    -- 4. Нет таблиц, колонок и ограничений регионов.
    SELECT COUNT(*) INTO v_n FROM (
        SELECT table_name FROM information_schema.tables WHERE table_schema = 'public' AND table_name ILIKE '%region%'
        UNION ALL
        SELECT table_name || '.' || column_name FROM information_schema.columns
         WHERE table_schema = 'public' AND column_name ILIKE '%region%'
        UNION ALL
        SELECT conname FROM pg_constraint WHERE connamespace = 'public'::regnamespace AND conname ILIKE '%region%'
    ) t;
    check_code := 'no_regions'; ok := v_n = 0; details := v_n || ' region objects'; RETURN NEXT;

    -- 5. Уникальность кодов.
    SELECT COUNT(*) INTO v_n FROM (SELECT code FROM cities GROUP BY code HAVING COUNT(*) > 1) t;
    check_code := 'city_codes_unique'; ok := v_n = 0; details := v_n || ' duplicates'; RETURN NEXT;
    SELECT COUNT(*) INTO v_n FROM (SELECT code FROM locations GROUP BY code HAVING COUNT(*) > 1) t;
    check_code := 'location_codes_unique'; ok := v_n = 0; details := v_n || ' duplicates'; RETURN NEXT;
    SELECT COUNT(*) INTO v_n FROM (SELECT code FROM world_events GROUP BY code HAVING COUNT(*) > 1) t;
    check_code := 'event_codes_unique'; ok := v_n = 0; details := v_n || ' duplicates'; RETURN NEXT;

    -- 6. Уровни открытия: 1…50; стартовый город — один, «Верхний Эльдран» (upper_eldran), уровень 1.
    SELECT COUNT(*) INTO v_n FROM cities WHERE unlock_level NOT BETWEEN 1 AND 50;
    check_code := 'city_unlock_levels_valid'; ok := v_n = 0; details := v_n || ' out of range'; RETURN NEXT;
    SELECT COUNT(*) INTO v_n FROM locations WHERE unlock_level NOT BETWEEN 1 AND 50;
    check_code := 'location_unlock_levels_valid'; ok := v_n = 0; details := v_n || ' out of range'; RETURN NEXT;
    SELECT COUNT(*) INTO v_n FROM cities WHERE is_start AND code = 'upper_eldran' AND unlock_level = 1 AND kind = 'permanent';
    check_code := 'start_city_upper_eldran'; ok := v_n = 1; details := 'start cities matching: ' || v_n; RETURN NEXT;
    SELECT MIN(unlock_level), MAX(unlock_level) INTO v_min, v_max FROM cities WHERE kind = 'permanent';
    check_code := 'permanent_levels_span_1_to_50'; ok := v_min = 1 AND v_max = 50;
    details := 'min ' || COALESCE(v_min, 0) || ', max ' || COALESCE(v_max, 0); RETURN NEXT;

    -- 7. Коэффициенты риска 0.00–1.00; у каждой локации есть город.
    SELECT COUNT(*) INTO v_n FROM locations WHERE risk_coefficient NOT BETWEEN 0 AND 1;
    check_code := 'risk_range'; ok := v_n = 0; details := v_n || ' out of range'; RETURN NEXT;
    SELECT COUNT(*) INTO v_n FROM locations l LEFT JOIN cities c ON c.id = l.city_id WHERE c.id IS NULL;
    check_code := 'locations_have_city'; ok := v_n = 0; details := v_n || ' orphans'; RETURN NEXT;

    -- 8. Доступ раньше нужного уровня невозможен; на нужном уровне постоянный город открыт.
    SELECT COUNT(*), string_agg(c.code, ', ') INTO v_n, v_list
      FROM cities c
      LEFT JOIN world_events e ON e.id = c.world_event_id
     WHERE world_city_access(c.id, GREATEST(c.unlock_level, COALESCE(e.min_level, 1)) - 1,
                             COALESCE(e.starts_at, NOW())) IS TRUE;
    check_code := 'no_city_access_below_level'; ok := v_n = 0; details := COALESCE(v_list, 'none'); RETURN NEXT;
    SELECT COUNT(*), string_agg(c.code, ', ') INTO v_n, v_list
      FROM cities c WHERE c.kind = 'permanent' AND world_city_access(c.id, c.unlock_level) IS NOT TRUE;
    check_code := 'permanent_city_open_at_level'; ok := v_n = 0; details := COALESCE(v_list, 'none'); RETURN NEXT;
    SELECT COUNT(*), string_agg(l.code, ', ') INTO v_n, v_list
      FROM locations l WHERE world_location_access(l.id, l.unlock_level - 1, NOW(), ARRAY[COALESCE(l.required_quest_code, '')]) IS TRUE;
    check_code := 'no_location_access_below_level'; ok := v_n = 0; details := COALESCE(v_list, 'none'); RETURN NEXT;

    -- 9. Календарь событий: окно, часовой пояс, статусы и история запусков согласованы.
    SELECT COUNT(*) INTO v_n FROM world_events e
     WHERE (starts_at IS NOT NULL AND ends_at IS NOT NULL AND ends_at <= starts_at)
        OR (status IN ('scheduled', 'active') AND (starts_at IS NULL OR ends_at IS NULL))
        OR NOT EXISTS (SELECT 1 FROM pg_timezone_names z WHERE z.name = e.timezone);
    check_code := 'event_windows_valid'; ok := v_n = 0; details := v_n || ' invalid events'; RETURN NEXT;
    SELECT COUNT(*) INTO v_n FROM world_events e
     WHERE (e.status = 'active') <> EXISTS (SELECT 1 FROM world_event_runs r WHERE r.world_event_id = e.id AND r.status = 'active');
    check_code := 'active_events_have_open_run'; ok := v_n = 0; details := v_n || ' mismatches'; RETURN NEXT;
    SELECT COUNT(*) INTO v_n FROM world_event_runs WHERE (status = 'active') <> (closed_at IS NULL);
    check_code := 'event_runs_closed_correctly'; ok := v_n = 0; details := v_n || ' mismatches'; RETURN NEXT;

    -- 10. Нет автоматических удалений: ни одно FK на cities / locations / world_events не каскадное.
    SELECT COUNT(*) INTO v_n FROM pg_constraint
     WHERE contype = 'f' AND confdeltype IN ('c', 'n', 'd')
       AND confrelid IN ('cities'::regclass, 'locations'::regclass, 'world_events'::regclass);
    check_code := 'no_cascade_deletes'; ok := v_n = 0; details := v_n || ' cascading/nulling FKs'; RETURN NEXT;
    SELECT COUNT(*) INTO v_n FROM cities c WHERE c.kind = 'event'
       AND (SELECT COUNT(*) FROM locations l WHERE l.city_id = c.id) = 4;
    check_code := 'event_cities_persist'; ok := v_n = 3; details := 'event cities with 4 locations: ' || v_n; RETURN NEXT;
END
$$;

CREATE TABLE IF NOT EXISTS users (
    id                  SERIAL PRIMARY KEY,
    login               VARCHAR(20)  NOT NULL,
    email               VARCHAR(254) NOT NULL,
    password_hash       TEXT         NOT NULL,
    -- Только в БД (в UI/API не используется). NULL допустим: поле не запрашивается.
    gender              VARCHAR(6)   CHECK (gender IN ('male', 'female')),
    -- Путь к аватару; по умолчанию — стабильный статический аватар.
    avatar_path         TEXT         NOT NULL DEFAULT '/avatars/default.svg',
    -- Игровые параметры. DEFAULT — стартовые значения нового игрока (общие для всех).
    level               INTEGER      NOT NULL DEFAULT 1   CHECK (level >= 1),
    health              INTEGER      NOT NULL DEFAULT 75  CHECK (health >= 0),
    max_health          INTEGER      NOT NULL DEFAULT 75  CHECK (max_health > 0),
    experience          INTEGER      NOT NULL DEFAULT 0   CHECK (experience >= 0),
    experience_to_next  INTEGER      NOT NULL DEFAULT 5   CHECK (experience_to_next > 0),
    silver              INTEGER      NOT NULL DEFAULT 200 CHECK (silver >= 0),
    rubies              INTEGER      NOT NULL DEFAULT 0   CHECK (rubies >= 0),
    -- Характеристики персонажа (стартовое значение — 3). Повышаются за серебро:
    -- цена = квадрат текущего значения (см. backend/src/constants/character.constants.js).
    strength            INTEGER      NOT NULL DEFAULT 3   CHECK (strength >= 1),
    giftedness          INTEGER      NOT NULL DEFAULT 3   CHECK (giftedness >= 1),
    constitution        INTEGER      NOT NULL DEFAULT 3   CHECK (constitution >= 1),
    luck                INTEGER      NOT NULL DEFAULT 3   CHECK (luck >= 1),
    attack_skill        INTEGER      NOT NULL DEFAULT 3   CHECK (attack_skill >= 1),
    defense_skill       INTEGER      NOT NULL DEFAULT 3   CHECK (defense_skill >= 1),
    -- Карма одним числом: > 0 — светлая, < 0 — тёмная. Получение кармы противоположного
    -- цвета сначала гасит накопленную (тёмная 10 + светлая 11 = светлая 1, тёмная 0).
    karma               INTEGER      NOT NULL DEFAULT 0,
    -- Город, где находится персонаж. Новый персонаж начинает в стартовом городе (cities.is_start).
    current_city_id     SMALLINT     NOT NULL DEFAULT world_start_city_id() REFERENCES cities(id) ON DELETE RESTRICT,
    CONSTRAINT users_health_range CHECK (health <= max_health),
    email_verified_at   TIMESTAMPTZ,
    password_changed_at TIMESTAMPTZ,
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

-- Уникальность без учёта регистра. Имена индексов используются backend'ом
-- (user.repository.js) для определения, какое поле занято.
CREATE UNIQUE INDEX IF NOT EXISTS users_login_lower_key ON users (lower(login));
CREATE UNIQUE INDEX IF NOT EXISTS users_email_lower_key ON users (lower(email));

-- Работы. Одна активная работа на игрока (частичный UNIQUE-индекс). Награда (silver, karma)
-- фиксируется при взятии работы; karma > 0 — светлая, < 0 — тёмная, 0 — нейтральная.
-- По окончании времени (ends_at) игрок нажимает «Принять оплату»: только тогда серебро и карма
-- зачисляются (status → completed). При отмене не зачисляется ничего (status → cancelled).
-- Время — только серверное (NOW()).
CREATE TABLE IF NOT EXISTS work_sessions (
    id          BIGSERIAL    PRIMARY KEY,
    user_id     INTEGER      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    kind        VARCHAR(16)  NOT NULL CHECK (kind IN ('gate', 'field', 'robbery')),
    hours       SMALLINT     NOT NULL CHECK (hours BETWEEN 1 AND 8),
    silver      INTEGER      NOT NULL CHECK (silver >= 0),
    karma       INTEGER      NOT NULL,
    status      VARCHAR(10)  NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'completed', 'cancelled')),
    started_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    ends_at     TIMESTAMPTZ  NOT NULL,
    settled_at  TIMESTAMPTZ
);

CREATE UNIQUE INDEX IF NOT EXISTS work_sessions_one_active_per_user ON work_sessions (user_id) WHERE status = 'active';
CREATE INDEX IF NOT EXISTS work_sessions_user_recent ON work_sessions (user_id, id DESC);
